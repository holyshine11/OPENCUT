// 요리드립(@yoridrip) 채널의 쇼츠 20여 편과 롱폼 6편을 보고 정리한 편집 스타일.
// 채널 색이 바뀌면 이 파일만 고친다. 프롬프트는 서버 라우트가 그대로 Claude에 넘긴다
import { ADJUST_PRESETS } from "@/effects/definitions/adjust-presets";
import { TRANSITION_TYPES } from "@/transitions";

const CHANNEL_STYLE = `
# 채널: 요리드립 (Cooking Drip)
남편이 요리하고, 아내가 옆에서 지켜보며 한마디씩 얹는 집밥 요리 채널이다. 화면은 손과 재료 클로즈업(탑뷰·근접)이고 얼굴은 거의 안 나온다.
내레이션은 아내 1인칭 TTS이고 "~합니다/~네요/~답니다" 체로 짧게 끊는다. 레시피 정보와 남편 놀리기(드립)가 번갈아 나온다.

## 쇼츠(세로, 15~45초, 길어도 70초)
- 첫 1.5초: 완성 음식이나 가장 센 장면 + 훅 한 줄. 훅 자막은 두 줄로 크게.
- 본문: 한 컷 1.5~3초. 재료 투입 → 손질 → 조리 → 완성 순서. 계량은 숫자로 말한다("고춧가루 한 큰술", "약불 5분").
- 중간에 "오늘의 킥"(의외의 재료·방법) 한 번, 가짜 끝("끝! …은 아니죠") 같은 반전 한 번.
- 끝: 한 입 먹는 장면 + 맛 평가를 하다 말고 끊거나("맛은 어떻냐고요? 오늘도 남편이…"), 질문으로 댓글을 부른다("이 정도면 남편이 잘한 건가요?").
- 자막은 내레이션을 그대로 받아 적지 않는다. 내레이션보다 짧고 더 센 요약이다.
  예) 내레이션 "표정만 백종원입니다" → 자막 "표정은 거의 백종원급" / "킹받는데 저녁은 먹어야 하니 참습니다" → "착한 내가 참는다" / 계량 컷은 "한 봉지의 2/3 정도 뿌려줌"
- 자막은 화면 아래 가운데, 한 번에 한 줄(훅만 두 줄), 14자 안쪽.

## 롱폼(가로, 2.5~8분)
- 도입 10초: 왜 이 요리인지(유명 맛집 재현, 방송 레시피 검증, 제철 재료) + "오늘도 남편한테 시켜봤습니다".
- 본문: 한 컷 3~6초, 과정 설명은 친절하게, 실수와 수습도 그대로 보여 준다("여기서 저희가 작은 실수를 하나 했지 뭐예요").
- 끝: 시식 평가 + 고정 멘트 계열("오늘도 남편 덕분에 맛있는 한끼 잘 얻어 먹었습니다").

## 드립 결
- 남편을 깎아내리지만 결국 맛은 인정한다("괜히 의심했습니다").
- 살림 디스("택배는 저한테 들게 하고 힘은 이럴 때 씁니다"), 과장("눈대중이 아니라 거의 운에 맡깁니다"), 재료 의인화("청국장도 치즈와의 합방에 당황한 것 같습니다"), 말장난('소'라에 '소'주).
- 욕설·비하·음식 낭비 조롱은 하지 않는다. 화면에 없는 재료나 과정을 지어내지 않는다.

## 제목
- 쇼츠: "감히 OO에 OO를 넣었습니다?", "OO, OO 대신 OO?", "OO 레시피 따라 해봤습니다", "남편이 OO를 …" 계열. 40자 안쪽, 핵심 음식명이 앞쪽.
- 롱폼: 맛집·방송명 + 재현/검증 + 핵심 비법 숫자.
`;

// 매번 같은 틀이 나오지 않게 실행할 때마다 하나씩 뽑아 준다
const HOOKS = [
	"도발형: \"감히 OO에 OO를 넣었습니다?\"",
	"결과 먼저형: 완성 장면에 \"이게 집에서 된다고요?\" 같은 한 줄",
	"고발형: \"남편이 또 사고를 칩니다\"로 시작해 이상한 재료를 보여 준다",
	"검증형: \"OO 레시피, 진짜 O분이면 될까요?\"",
	"숫자형: 핵심 비법 숫자를 맨 앞에(\"딱 7분만 갈면 됩니다\")",
	"질문형: 시청자에게 바로 묻는다(\"OO에 이거 넣어 보신 분?\")",
];
const HUMOR = [
	"살림 디스(집안일은 안 하면서 요리만 열심)",
	"재료 의인화(재료가 당황하거나 억울해한다)",
	"과장 비유(표정만 셰프, 손놀림은 장인)",
	"말장난(재료 이름으로 언어유희 한 번)",
	"속마음 자막(내레이션은 점잖게, 자막은 속마음)",
	"가짜 끝(\"끝! …은 아니죠\")",
];
const ENDINGS = [
	"맛 평가를 하다 말고 끊는 클리프행어(\"오늘도 남편이…\")",
	"댓글을 부르는 질문(\"이 정도면 잘한 건가요?\")",
	"반전 인정(\"괜히 의심했습니다\")",
	"다음 편 예고나 후일담 한 줄(\"며칠이 지났는데도 계속 생각나네요\")",
];

const pick = (items: string[]) => items[Math.floor(Math.random() * items.length)];

export interface PromptClip {
	/** 프롬프트와 계획에서 쓰는 번호. c01부터 */
	id: string;
	name: string;
	duration: number;
	/** 스틸 시트에 왼쪽부터 놓인 프레임의 시각(초) */
	times: number[];
	sheetFile: string;
}

export function buildPrompt({
	clips,
	canvas,
	hasVoice,
	recent,
}: {
	clips: PromptClip[];
	canvas: { width: number; height: number };
	/** 내레이션 음성을 만들 수 있는지. 없으면 자막만으로 이야기를 끌고 간다 */
	hasVoice: boolean;
	/** 최근에 쓴 훅. 겹치지 않게 한다 */
	recent: string[];
}): string {
	const isShort = canvas.height > canvas.width;
	return `너는 이 유튜브 채널의 전담 편집자다. 아래 채널 스타일대로 촬영 원본을 편집 계획(JSON)으로 만든다.
${CHANNEL_STYLE}
# 이번 영상
- 화면: ${canvas.width}x${canvas.height} → ${isShort ? "쇼츠. 완성 길이 20~45초" : "롱폼. 완성 길이 2.5~5분(원본이 짧으면 그만큼만)"}
- ${hasVoice ? "내레이션은 TTS로 읽는다. 한국어 TTS는 1초에 6~7자를 읽으니, 한 컷의 내레이션은 (컷 길이 × 6)자를 넘기지 않는다." : "내레이션 음성이 없다. narration은 빈 문자열로 두고 자막(caption)만으로 이야기를 끌고 간다."}
- 이번 변주(매번 다르게 만들기 위한 지정값이다. 꼭 따른다):
  - 훅: ${pick(HOOKS)}
  - 드립: ${pick(HUMOR)} + 네가 영상을 보고 고른 것 하나
  - 엔딩: ${pick(ENDINGS)}
${recent.length > 0 ? `- 최근 영상에서 이미 쓴 훅이다. 같은 문장 틀을 피한다:\n${recent.map((hook) => `  - ${hook}`).join("\n")}` : ""}

# 촬영 원본
클립마다 스틸 시트(가로로 이어 붙인 프레임, 왼쪽부터 아래 시각) 파일이 현재 폴더에 있다. Read로 전부 열어 본다.
${clips.map((clip) => `- ${clip.id} "${clip.name}" ${clip.duration.toFixed(1)}초 → ${clip.sheetFile} (프레임 시각: ${clip.times.map((time) => time.toFixed(1)).join(", ")}초)`).join("\n")}

# 작업 순서
1. 컷 편집: 시트를 보고 무슨 요리인지, 클립마다 무슨 과정인지 파악한다. 쓸 구간만 고르고 순서를 정한다. 흔들리거나 아무 일도 없는 구간, 같은 동작 반복은 버린다. 가장 맛있어 보이는 완성 장면을 맨 앞 훅으로 한 번 당겨 써도 된다.
2. 컨셉·대본: 이 영상만의 한 줄 컨셉을 정하고 컷마다 내레이션을 쓴다. 화면에 보이는 것만 말한다. 계량이 안 보이면 지어내지 말고 동작을 말한다.
3. 자막: 컷마다 자막을 쓴다. 내레이션의 받아쓰기가 아니라 더 짧고 센 요약이다. 14자 안쪽, 훅만 줄바꿈(\\n) 한 번 허용.
4. 효과·색감: 음식 색에 맞는 색 보정 하나와, 장면이 크게 바뀌는 자리(시간 경과, 완성)에만 전환을 넣는다. 전환은 전체에서 0~3번.
5. 검토: 설치돼 있으면 yt-script, yt-package, yt-seo 스킬 규칙으로 훅·제목·설명·태그를 점검한다. WebSearch로 이 요리의 요즘 검색어·화제(방송, 맛집, 제철)를 한두 번 확인해 제목과 태그에 반영한다. 그다음 계획을 처음부터 다시 읽고 ①첫 컷이 1.5초 안에 궁금증을 만드는지 ②내레이션 길이가 컷 길이에 맞는지 ③같은 구간을 두 번 쓰지 않았는지(훅 제외) ④드립이 3컷에 한 번꼴로 들어갔는지 ⑤모든 start/end가 클립 길이 안인지 확인하고 고친다.

단계를 넘어갈 때마다 "[1/5] 컷 편집: (한 줄 요약)" 형식으로 한 줄씩 말한다. 사용자가 이 줄을 진행 화면에서 본다.

# 출력
마지막 메시지는 아래 JSON 하나만 낸다(설명·코드 펜스 없이).
{
  "concept": "한 줄 컨셉",
  "hook": "첫 컷 내레이션 또는 자막 그대로",
  "look": ${ADJUST_PRESETS.map((preset) => `"${preset.id}"`).join(" | ")},
  "beats": [
    { "clip": "c01", "start": 0.0, "end": 2.5, "narration": "…", "caption": "…", "transition": null | ${TRANSITION_TYPES.map((type) => `"${type}"`).join(" | ")} }
  ],
  "youtube": { "title": "…", "description": "첫 두 줄에 핵심 검색어, 재료·계량 목록, 해시태그 3개", "tags": ["…"] },
  "review": ["검토하면서 고친 점이나 사용자가 확인할 점"]
}
- beats는 완성 영상의 컷 순서다. start/end는 그 클립 안의 초이고 end - start는 ${isShort ? "1.2~4" : "2~8"}초.
- transition은 그 컷에서 다음 컷으로 넘어갈 때의 전환이다.
`;
}
